import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {applyTrustConsistency,validateTrustConsistency} from './trust-consistency-integrator.mjs';

const here=path.dirname(fileURLToPath(import.meta.url));
const out=path.resolve(here,'../docs/franchise-ssg-preview');
const manifestPath=path.join(out,'route-manifest.json');
const reportPath=path.join(out,'v11-52-release-candidate.json');
const manifest=JSON.parse(await fs.readFile(manifestPath,'utf8'));
const report=JSON.parse(await fs.readFile(reportPath,'utf8'));
if(manifest.uiVersion!=='11.52'||report.uiVersion!=='11.52')throw new Error('Trust consistency requires v11.52 release candidate');
if(manifest.v11_52?.candidateSetChanged!==false||manifest.v11_52?.indexPolicyChanged!==false||manifest.v11_52?.dataSemanticsChanged!==false||manifest.v11_52?.productionDeployed!==false)throw new Error('Trust consistency immutable contract mismatch');
await fs.copyFile(path.join(here,'trust-consistency.css'),path.join(out,'assets/trust-consistency.css'));
const applied=applyTrustConsistency(out);
const validation=validateTrustConsistency(out);
manifest.v11_52.trustConsistencyUx=true;
report.trustConsistencyUx=true;
await fs.writeFile(manifestPath,JSON.stringify(manifest,null,2)+'\n','utf8');
await fs.writeFile(reportPath,JSON.stringify(report,null,2)+'\n','utf8');
console.log(JSON.stringify({v11_52TrustConsistency:'PASS',...validation,...applied,rcReady:report.rcReady===true,productionDeployed:false},null,2));
