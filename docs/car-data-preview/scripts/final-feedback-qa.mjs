import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
import {newQaPage} from './qa-photo-fixture.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const data=p=>JSON.parse(read(p));
const base=process.env.CAR_PREVIEW_BASE||'http://127.0.0.1:4173/car-data-preview';
const recall=data('data/recalls.json');
const kia=read('cars/kia/index.html');
assert.match(kia,/플러그인 하이브리드 · 전기 전비<\/small><b>5\.1<\/b> km\/kWh/);
assert.doesNotMatch(kia,/플러그인 하이브리드<\/small><b>5\.1<\/b> km\/L/);
const graph=JSON.parse(kia.match(/<script type="application\/ld\+json">([^<]+)<\/script>/)?.[1]||'{}')['@graph'];
const list=graph.find(item=>item['@type']==='ItemList');
assert.equal(list.numberOfItems,24);
assert.equal(list.itemListElement.length,24);
const ion=read('cars/hyundai/ioniq-6-ce1/index.html');
assert.match(ion,/항속형[^<]*2WD[^<]*18인치[^<]*<\/th><td>전기<\/td><td>6 km\/kWh/);
assert.match(ion,/562km/);
assert.match(ion,/>전기 · N ·/);
const home=read('index.html'),recalls=read('recalls/index.html');
assert.match(home,/<main class="editorial-home">/);
assert.equal((home.match(/class="home-car"/g)||[]).length,6);
assert.match(home,/media-policy\/#vehicle-photo-credits/);
assert.match(recalls,new RegExp(`자료 확인 ${recall.data_as_of}`));
assert.match(recalls,/전체·최신 리콜 목록이 아닙니다/);
const evComparison=read('compare/ioniq5-vs-ev6/index.html');
assert.match(evComparison,/comparison-lead[^>]*>[^<]*(?:적음|동일)/);
assert.match(evComparison,/300원\/kWh는 비교용 초기값/);
const browser=await chromium.launch(process.env.CAR_PREVIEW_CHROME_PATH?{executablePath:process.env.CAR_PREVIEW_CHROME_PATH}:{});
try{
 const page=await newQaPage(browser,{viewport:{width:375,height:812}});
 await page.goto(base+'/cars/kia/ev6/',{waitUntil:'networkidle'});
 await page.locator('#variantButtons [data-variant-index="4"]').click();
 assert.match(await page.locator('#effValue').textContent(),/4\.5 km\/kWh/);
 const url=await page.locator('a[href*="tools/annual-cost/"]').first().getAttribute('href');
 assert.equal(new URL(url,base+'/cars/kia/ev6/').searchParams.get('variant'),'cv-lr-awd-20');
 await page.locator('a[href*="tools/annual-cost/"]').first().click();
 await page.waitForURL('**/tools/annual-cost/**');
 await page.waitForFunction(()=>document.documentElement.dataset.costMode==='reviewed'&&document.querySelector('#variant')?.value==='cv-lr-awd-20');
 assert.equal(await page.locator('#variant').inputValue(),'cv-lr-awd-20');
 await page.locator('#km').fill('30000');
 await page.locator('#price').fill('320');
 await page.waitForFunction(()=>{const q=new URLSearchParams(location.search);return q.get('variant')==='cv-lr-awd-20'&&q.get('km')==='30000'&&q.get('cprice_electric')==='320'});
 await page.waitForFunction(()=>document.querySelector('#total')?.textContent?.trim()!=='충전단가 입력');
 const result=await page.locator('#total').textContent();
 const shared=page.url();await page.goto(shared,{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('#variant')?.value==='cv-lr-awd-20'&&document.querySelector('#price')?.value==='320');
 await page.waitForFunction(()=>document.querySelector('#total')?.textContent?.trim()!=='충전단가 입력');
 assert.equal(await page.locator('#km').inputValue(),'30000');
 assert.equal(await page.locator('#total').textContent(),result);
 await page.goto(base+'/cars/hyundai/ioniq-6-ce1/',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.dossier-table tbody tr').filter({hasText:'562km'}).count(),1);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
 await page.close();
 console.log('PASS final feedback: source units, recall scope, photo context, full-range sampling, EV6 variant handoff and shared-cost round trip.');
}finally{await browser.close()}
